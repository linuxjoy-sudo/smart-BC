#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn converts_common_traditional() {
        assert_eq!(to_simplified("明天早上八點鐘，我去醫院"), "明天早上八点钟，我去医院");
    }

    #[test]
    fn converts_repeated_chars() {
        assert_eq!(to_simplified("再見再見"), "再见再见");
    }

    #[test]
    fn keeps_simplified_unchanged() {
        assert_eq!(to_simplified("你好，去医院"), "你好，去医院");
    }

    #[test]
    fn empty_input() {
        assert_eq!(to_simplified(""), "");
    }
}
